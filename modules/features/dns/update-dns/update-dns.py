#!/usr/bin/env python3
"""Update /etc/resolv.conf from Android's current DNS configuration.

Runs `sudo /system/bin/dumpsys connectivity`, parses the DNS servers of the
currently connected networks, prefers the WiFi one, and rewrites /etc/resolv.conf.

Usage:
    update-dns
    UPDATE_DNS_NO_SUDO=1 update-dns   # run dumpsys without sudo (for testing)

Environment overrides:
    DUMPSYS_CMD       path to dumpsys (default: /system/bin/dumpsys)
    RESOLV_CONF       target file (default: /etc/resolv.conf)
"""

import os
import re
import subprocess
import sys

RESOLV_CONF = os.environ.get("RESOLV_CONF", "/etc/resolv.conf")
DUMPSYS_CMD = os.environ.get("DUMPSYS_CMD", "/system/bin/dumpsys")


def parse_dumpsys(text):
    """Parse `dumpsys connectivity` output into (active_default_id, networks).

    Each network dict: {id, transport, connected, has_internet, dns, domains}.
    """
    active_match = re.search(r"Active default network:\s*(\d+)", text)
    active_default = int(active_match.group(1)) if active_match else None

    networks = []
    for block in re.split(r"(?=NetworkAgentInfo\{)", text):
        id_match = re.search(r"NetworkAgentInfo\{network\{(\d+)\}", block)
        if not id_match:
            continue
        net_id = int(id_match.group(1))

        ni_match = re.search(r"ni\{([^}]*)\}", block)
        ni = ni_match.group(1) if ni_match else ""
        transport = (ni.split() or [""])[0].upper()
        connected = "CONNECTED" in ni

        # nc{[ ... ]} may contain nested brackets (Specifier: <...[mSubId = 3]>),
        # so use a greedy match up to the last "]}" of the block.
        nc_match = re.search(r"nc\{\[(.*)\]\}", block, re.S)
        nc = nc_match.group(1) if nc_match else ""
        has_internet = "INTERNET" in nc

        lp_match = re.search(r"lp\{\{(.*?)\}\}", block, re.S)
        lp = lp_match.group(1) if lp_match else ""

        dns = []
        dns_match = re.search(r"DnsAddresses:\s*\[(.*?)\]", lp, re.S)
        if dns_match:
            for ip in re.findall(r"/([0-9a-fA-F:.]+)", dns_match.group(1)):
                if ip not in dns:
                    dns.append(ip)

        domains = None
        dom_match = re.search(r"Domains:\s*(\S+)", lp)
        if dom_match and dom_match.group(1) != "null":
            domains = dom_match.group(1)

        if connected and dns:
            networks.append({
                "id": net_id,
                "transport": transport,
                "dns": dns,
                "domains": domains,
                "has_internet": has_internet,
            })

    return active_default, networks


def pick_network(active_default, networks):
    """Prefer WiFi, then the active default network, then any INTERNET network."""
    wifi = [n for n in networks if "WIFI" in n["transport"]]
    if wifi:
        for n in wifi:
            if n["id"] == active_default:
                return n
        return wifi[0]
    if active_default is not None:
        for n in networks:
            if n["id"] == active_default:
                return n
    for n in networks:
        if n["has_internet"]:
            return n
    return networks[0] if networks else None


def get_dumpsys_output():
    if os.environ.get("UPDATE_DNS_NO_SUDO"):
        return subprocess.run(
            [DUMPSYS_CMD, "connectivity"], capture_output=True, text=True)
    return subprocess.run(
        ["sudo", DUMPSYS_CMD, "connectivity"], capture_output=True, text=True)


def main():
    proc = get_dumpsys_output()
    if proc.returncode != 0:
        sys.stderr.write(
            "`dumpsys connectivity` failed (%d):\n%s\n"
            % (proc.returncode, proc.stderr))
        return 1

    active_default, networks = parse_dumpsys(proc.stdout)
    chosen = pick_network(active_default, networks)
    if chosen is None:
        sys.stderr.write(
            "No usable DNS servers found in `dumpsys connectivity` output\n")
        return 1

    lines = [
        "# generated by update-dns from `dumpsys connectivity`",
        "# source: network {} ({}) active_default={}".format(
            chosen["id"], chosen["transport"], active_default),
    ]
    if chosen["domains"]:
        lines.append("search " + chosen["domains"])
    lines += ["nameserver " + ip for ip in chosen["dns"]]
    content = "\n".join(lines) + "\n"

    tmp = RESOLV_CONF + ".new"
    with open(tmp, "w") as f:
        f.write(content)
    os.replace(tmp, RESOLV_CONF)  # atomically replaces a symlink as well

    print(content)
    print("wrote {} ({} nameservers, network {} {})".format(
        RESOLV_CONF, len(chosen["dns"]), chosen["id"], chosen["transport"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
